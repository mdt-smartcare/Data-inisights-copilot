    def _is_trino(self) -> bool:
        """Check if the database is Trino/Presto."""
        url_lower = self._db_url.lower()
        return url_lower.startswith("trino://") or url_lower.startswith("presto://")
    
    def _get_trino_schema(self) -> Optional[str]:
        """Extract schema from Trino URL: trino://user:pass@host:port/catalog/schema."""
        from urllib.parse import urlparse
        parsed = urlparse(self._db_url)
        path_parts = parsed.path.strip('/').split('/')
        return path_parts[1] if len(path_parts) > 1 else None
    
    def _get_engine(self) -> Engine:
        """
        Get or create a database engine with thread-safe connection pooling.
        
        Uses ThreadSafeEngineCache for:
        - Thread safety
        - Tenant isolation
        - Connection health checks
        """
        if self._engine is not None:
            return self._engine
        
        # Use thread-safe cache with tenant isolation and fast-fail timeout
        try:
            # Add connect_timeout for PostgreSQL/MySQL to fail fast when database is unavailable
            # DuckDB and Trino don't support connect_timeout
            engine_kwargs = {}
            if not self._is_duckdb() and not self._is_trino():
                engine_kwargs["connect_args"] = {"connect_timeout": 3}
            
            self._engine = self._engine_cache.get_or_create(
                db_url=self._db_url,
                tenant_id=self._tenant_id,
                **engine_kwargs
            )
            
            # Load ICU extension for DuckDB
            if self._is_duckdb():
                try:
                    with self._engine.connect() as conn:
                        conn.execute(text("INSTALL icu; LOAD icu;"))
                        conn.commit()
                    logger.debug("Loaded ICU extension for DuckDB")
                except Exception as e:
                    logger.debug(f"ICU extension not loaded (may already be loaded): {e}")
            
            return self._engine
            
        except Exception as e:
            logger.error(f"Failed to get database engine: {e}")
            raise
    
    def _get_cache_key(self) -> str:
        """Get a normalized cache key for the database URL."""
        db_url = self._db_url
        if db_url.startswith("postgres://"):
            db_url = db_url.replace("postgres://", "postgresql://", 1)
        return db_url

    def _discover_tables(self) -> List[str]:
        """
        Discover available tables in the database, excluding internal/metadata tables.
        
        Uses a global cache to avoid re-querying the database on every request.
        """
        # Check instance cache first
        if self._table_names:
            return self._table_names
        
        # Check global cache (shared across SQLService instances with same db_url)
        cache_key = self._get_cache_key()
        if cache_key in _TABLE_NAMES_CACHE:
            self._table_names = _TABLE_NAMES_CACHE[cache_key]
            logger.debug(f"Using cached table list ({len(self._table_names)} tables)")
            return self._table_names
        
        engine = self._get_engine()
        
        try:
            with engine.connect() as conn:
                all_tables = []
                
                if self._is_duckdb():
                    # For DuckDB: include both tables AND views (uploaded files are registered as views)
                    try:
                        result = conn.execute(text("""
                            SELECT table_name 
                            FROM information_schema.tables 
                            WHERE table_schema = 'main'
                            ORDER BY table_name
                        """))
                        all_tables = [row[0] for row in result]
                    except Exception as e:
                        logger.debug(f"DuckDB information_schema query failed: {e}")
                        # Fallback: use SHOW TABLES
                        try:
                            result = conn.execute(text("SHOW TABLES"))
                            all_tables = [row[0] for row in result]
                        except Exception:
                            all_tables = []
                elif self._is_trino():
                    # For Trino/Presto: filter by schema from connection URL
                    target_schema = self._get_trino_schema()
                    if target_schema:
                        logger.debug(f"Trino: filtering to schema '{target_schema}'")
                        result = conn.execute(text("""
                            SELECT table_name 
                            FROM information_schema.tables 
                            WHERE table_type = 'BASE TABLE'
                            AND table_schema = :schema
                            ORDER BY table_name
                        """), {"schema": target_schema})
                    else:
                        logger.debug("Trino: no schema specified, fetching all tables")
                        result = conn.execute(text("""
                            SELECT table_name 
                            FROM information_schema.tables 
                            WHERE table_type = 'BASE TABLE'
                            ORDER BY table_name
                        """))
                    all_tables = [row[0] for row in result]
                else:
                    # For PostgreSQL, MySQL - use standard information_schema with BASE TABLE filter
                    try:
                        result = conn.execute(text("""
                            SELECT table_name 
                            FROM information_schema.tables 
                            WHERE table_type = 'BASE TABLE'
                            AND table_schema NOT IN ('pg_catalog', 'information_schema')
                            ORDER BY table_name
                        """))
                        all_tables = [row[0] for row in result]
                    except Exception:
                        try:
                            result = conn.execute(text("SHOW TABLES"))
                            all_tables = [row[0] for row in result]
                        except Exception:
                            all_tables = []
                
                # Filter out internal/metadata tables (those starting with underscore)
                self._table_names = [t for t in all_tables if not t.startswith('_')]
                
                # Store in global cache for reuse across instances
                _TABLE_NAMES_CACHE[cache_key] = self._table_names
                
                # Log only count on first discovery (not all table names to reduce log noise)
                logger.info(f"Discovered {len(self._table_names)} tables (cached for future requests)")
            
            return self._table_names
            
        except Exception as e:
            logger.error(f"Database connection failed: {e}")
            raise DatabaseConnectionError(
                f"Cannot connect to database. Please ensure the database is running and accessible."
            ) from e
    
    def get_schema_context(self, max_tables: int = 10) -> str:
        """
        Get database schema as context for LLM queries.
        
        Returns a formatted string describing tables and their columns with types.
        Highlights VARCHAR columns that contain date-like names and need casting.
        """
        if self._cached_schema:
            return self._cached_schema
        
        # This will raise DatabaseConnectionError if database is unavailable
        tables = self._discover_tables()[:max_tables]
        engine = self._get_engine()
        
        schema_parts = []
        varchar_date_columns = []  # Track VARCHAR columns that look like dates
        
        # Date-related column name patterns
        date_patterns = ['date', 'time', 'created', 'updated', 'modified', 'timestamp', '_at', '_on']
        
        try:
            with engine.connect() as conn:
                for table in tables:
                    try:
                        # Get column info
                        result = conn.execute(text(f"""
                            SELECT column_name, data_type, is_nullable
                            FROM information_schema.columns
                            WHERE table_name = :table
                            ORDER BY ordinal_position
                        """), {"table": table})
                        
                        columns = [(row[0], row[1], row[2]) for row in result]
                        
                        if columns:
                            col_parts = []
                            for name, dtype, nullable in columns[:30]:
                                null_indicator = "?" if nullable == 'YES' else ""
                                col_parts.append(f"{name} ({dtype}{null_indicator})")
                                
                                # Check if this is a VARCHAR column with a date-like name
                                if dtype.upper() == 'VARCHAR':
                                    name_lower = name.lower()
                                    if any(pattern in name_lower for pattern in date_patterns):
                                        varchar_date_columns.append(f"{table}.{name}")
                            
                            col_desc = ", ".join(col_parts)
                            if len(columns) > 30:
                                col_desc += f", ... and {len(columns) - 30} more columns"
                            schema_parts.append(f"- {table}: {col_desc}")
                    except Exception:
                        schema_parts.append(f"- {table}: (columns unavailable)")
            
            # Build final schema with warnings
            final_parts = ["Tables:\n" + "\n".join(schema_parts)]
            
            # Add explicit warning about VARCHAR date columns
            if varchar_date_columns:
                warning = "\n\nWARNING - VARCHAR DATE COLUMNS REQUIRE CASTING:\n"
                warning += "These columns store dates as VARCHAR. You MUST cast them before date operations:\n"
                for col in varchar_date_columns:
                    col_name = col.split('.')[-1]
                    warning += f"  - {col} -> CAST({col_name} AS TIMESTAMP)\n"
                warning += "\nREQUIRED PATTERNS:\n"
                warning += "  WHERE CAST(created_at AS TIMESTAMP) >= CURRENT_DATE - INTERVAL '1 year'\n"
                warning += "  DATE_TRUNC('month', CAST(created_at AS TIMESTAMP))"
                final_parts.append(warning)
            
            self._cached_schema = "\n".join(final_parts)
            return self._cached_schema
            
        except Exception as e:
            logger.error(f"Failed to get schema context: {e}")
            return f"Tables: {', '.join(tables)}"


